-- ============================================================
-- إجبار Supabase على إعادة تحميل صلاحيات قاعدة البيانات
-- ============================================================
-- السبب المحتمل: طبقة الـ API (PostgREST) تحتفظ بنسخة مخبّأة
-- من صلاحيات الجداول، ولا تلاحظ دائماً أوامر GRANT الجديدة
-- تلقائياً إذا نُفّذت مباشرة عبر SQL Editor. هذا الأمر يجبرها
-- على إعادة القراءة فوراً.
-- ============================================================

notify pgrst, 'reload schema';

-- تأكيد إضافي: تحقق من الصلاحية الحالية مرة أخرى بعد الأمر أعلاه
select grantee, column_name
from information_schema.column_privileges
where table_name = 'companies' and privilege_type = 'SELECT'
order by grantee, column_name;
